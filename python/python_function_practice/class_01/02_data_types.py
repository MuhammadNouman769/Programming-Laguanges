
''' ============= DATA Types ============== '''
# Integer
print(8)

# 1*10^308
print(1e308)
print(1e309)

# Decimal/Float
print(8.55)
print(1.7e308)
print(1.7e309)

# Boolean
print(True)
print(False)

# Text/String
print('hello world')

# complex 
print(5+6j)

# List 
print([1,2,3,4,5,6,7,8,9])

# Tuple 
print((1,2,3,4,5,6))

# Sets
print({1,2,3,4,5,6})

# Dictionary
print(
    {
        'name':'Numan',
        'age':'27',
        'gander':'male'
    }
)

print(type(2))
print(type([1,2,3,4]))
